//-1	not ascii num;
int	check_str_num(char *str)
{
	if (str[0] == '\0')
	{
		return (-1);
	}
	while (*str != '\0')
	{
		if (!((*str >= '0') && (*str <= '9')))
		{
			return (-1);
		}
		str++;
	}
	return (1);
}
